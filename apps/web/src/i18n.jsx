const I18nContext = createContext(null)
const LANG_KEY = 'tilcago.lang'

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem(LANG_KEY) || 'es'
    } catch {
      return 'es'
    }
  })

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo(() => {
    // Formato con punto decimal, igual que en el diseño (Bs 1,371.12)
    const nf = new Intl.NumberFormat('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    const t = (key, vars) => {
      let s = DICT[lang][key] ?? DICT.es[key] ?? key
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`))
      return s
    }
    // Elige el idioma de un valor { es, en } o devuelve el texto tal cual
    const L = (v) => (v && typeof v === 'object' ? v[lang] ?? v.es : v)
    const setLang = (l) => {
      setLangState(l)
      try {
        localStorage.setItem(LANG_KEY, l)
      } catch {
        /* sin almacenamiento: el idioma vale solo para esta visita */
      }
    }
    return { lang, setLang, t, L, num: (n) => nf.format(n), bs: (n) => `Bs ${nf.format(n)}` }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
